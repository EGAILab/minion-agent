"""L12-D012 (L12D012-F002): the Python port of Node v22.15.1 `path.win32.resolve` and its hook in
the certified resolver. Expectations are Node's own observations
(`data/node_win32_resolve.json`, generated by minion-agent-docs
assurance/layers/data/l12-d012/gen/gen_port_fixture.mjs), never values written by hand."""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

import pytest

from minion_agent.execution import filesystem

FIXTURE = json.loads(
    (Path(__file__).parent / "data" / "node_win32_resolve.json").read_text(encoding="utf-8")
)
BASE_ROWS = [r for r in FIXTURE["rows"] if "base" in r]
ENTRY_ROWS = [r for r in FIXTURE["rows"] if "entry" in r]
NORMALIZE_ROWS = [r for r in FIXTURE["rows"] if "normalize" in r]


@pytest.mark.parametrize("row", NORMALIZE_ROWS, ids=lambda r: r["normalize"])
def test_normalize_string_equals_node(row: dict[str, str]) -> None:
    """For a relative, device-free path not ending in a separator, Node's `path.win32.normalize` is
    exactly `normalizeString(path, true)` (a tail that does not end in a separator)."""
    assert filesystem._node_normalize_string(row["normalize"], True) == row["out"]


def _unused(*_: Any) -> Any:
    raise AssertionError("host state consulted where Node consults none")


@pytest.mark.parametrize("row", BASE_ROWS, ids=lambda r: f"{r['base']}|{r['input']}")
def test_port_equals_node_without_host_state(row: dict[str, str]) -> None:
    observed = filesystem.node_win32_resolve(
        [row["base"], row["input"]], inherited=_unused, process_cwd=_unused
    )
    assert observed == row["out"]


@pytest.mark.parametrize("row", ENTRY_ROWS, ids=lambda r: f"{r['entry']}|{r['input']}")
def test_port_equals_node_with_an_inherited_entry(row: dict[str, str]) -> None:
    def inherited(device: str) -> str | None:
        return row["entry"] if device.lower() == "a:" else None

    observed = filesystem.node_win32_resolve(
        ["C:\\x", row["input"]], inherited=inherited, process_cwd=lambda: "E:\\host"
    )
    assert observed == row["out"]


def test_fixture_is_nodes_own_output() -> None:
    assert FIXTURE["node"] == "v22.15.1" and FIXTURE["platform"] == "win32"
    assert len(BASE_ROWS) >= 40 and len(ENTRY_ROWS) == 7


def test_port_with_no_arguments_resolves_the_process_cwd() -> None:
    assert (
        filesystem.node_win32_resolve([], inherited=_unused, process_cwd=lambda: "E:\\w\\..\\v")
        == "E:\\v"
    )


@pytest.mark.parametrize(
    ("cwd", "path", "expected"),
    [
        ("C:\\x", "a:b", True),
        ("C:\\x", "A:", True),
        ("C:\\x", "c:b", False),  # the provider cwd's own drive
        ("C:\\x", "a:\\b", False),  # absolute
        ("C:\\x", "\\\\srv\\share", False),  # UNC is not drive-relative
        ("C:\\x", "b", False),
        ("C:\\x", "", False),
        ("\\\\srv\\share\\d", "c:b", True),
    ],
)
def test_other_drive_relative_classification(cwd: str, path: str, expected: bool) -> None:
    assert filesystem._is_other_drive_relative(cwd, path) is expected


@pytest.mark.skipif(sys.platform != "win32", reason="the per-drive entry exists only on win32")
def test_resolver_hook_reads_the_inherited_entry(monkeypatch: pytest.MonkeyPatch) -> None:
    from minion_agent.execution import _libuv_win32

    seen: list[str] = []

    def inherited(device: str) -> str | None:
        seen.append(device)
        return "A:\\deep"

    monkeypatch.setattr(_libuv_win32, "inherited_drive_cwd", inherited)
    assert filesystem.resolve_local_path("C:\\x", "a::/b") == "a:\\deep\\:\\b"
    assert seen == ["a:"]
    seen.clear()
    # same drive: no lookup (Node's own value, record section 2 row 8)
    assert filesystem.resolve_local_path("C:\\x", "c:d") == "c:\\x\\d"
    assert seen == []


@pytest.mark.skipif(sys.platform != "win32", reason="the per-drive entry exists only on win32")
def test_inherited_drive_cwd_absent_empty_and_long(monkeypatch: pytest.MonkeyPatch) -> None:
    import ctypes

    from minion_agent.execution import _libuv_win32

    assert _libuv_win32.inherited_drive_cwd("Q:") is None  # no =Q: entry in the test process
    values = {"=Q:": ""}

    class FakeKernel:
        @staticmethod
        def GetEnvironmentVariableW(name: str, buffer: Any, size: int) -> int:
            value = values[name]
            if not value:
                ctypes.set_last_error(0)
                return 0
            if len(value) >= size:
                return len(value) + 1
            buffer.value = value
            return len(value)

    monkeypatch.setattr(_libuv_win32, "_k32", FakeKernel)
    assert _libuv_win32.inherited_drive_cwd("Q:") == ""  # present but empty
    values["=Q:"] = "Q:\\" + "d" * 400  # longer than the first buffer: grown once
    assert _libuv_win32.inherited_drive_cwd("Q:") == values["=Q:"]
